     private String errorLabel(double pct) {
        if (pct <= 10) return "Very Low Error";
        if (pct <= 20) return "Low Error";
        if (pct <= 30) return "Moderate Error";
        if (pct <= 50) return "High Error";
        return "Very High Error";
    }
    
    private String r2Label(double r2) {
        if (r2 >= 0.90) return "Excellent fit";
        if (r2 >= 0.70) return "Good fit";
        if (r2 >= 0.50) return "Moderate fit";
        if (r2 >= 0.25) return "Weak fit";
        return "Very weak fit";
    }

    private String corrLabel(double r) {
        double a = Math.abs(r);                    
        if (a >= 0.90) return "Very Strong";
        if (a >= 0.70) return "Strong";
        if (a >= 0.50) return "Moderate";
        if (a >= 0.25) return "Weak";
        return "Very Weak";
    }
    
