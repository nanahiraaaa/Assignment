    private void analyzeActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_analyzeActionPerformed
        // TODO add your handling code here:

        try{
            Instances data = DataSource.read(datas);
            data.setClassIndex(1);
            
//            data.randomize(new Random(42));

            // 3. 80/20 split
            int trainSize = (int) Math.round(data.numInstances() * 0.8);
            int testSize  = data.numInstances() - trainSize;

            Instances train = new Instances(data, 0, trainSize);
            Instances test  = new Instances(data, trainSize, testSize);
            
            SimpleLinearRegression model = new SimpleLinearRegression();
            model.buildClassifier(data);

            Evaluation evalTrain = new Evaluation(train);
            evalTrain.evaluateModel(model, train);
            
            Evaluation evalTest = new Evaluation(train);   // note: train here
            evalTest.evaluateModel(model, test);

            double maeTr  = evalTrain.meanAbsoluteError();
            double rmseTr = evalTrain.rootMeanSquaredError();
            double rTr    = evalTrain.correlationCoefficient();
            double r2Tr   = rTr * rTr;

            double maeTe  = evalTest.meanAbsoluteError();
            double rmseTe = evalTest.rootMeanSquaredError();
            double rTe    = evalTest.correlationCoefficient();
            double r2Te   = rTe * rTe;

            //            System.out.println("===== SIMPLE LINEAR REGRESSION EVALUATION =====");
            MAE1.setText(String.format("MAE : %.4f%n-%s", maeTr, errorLabel(maeTr)));
            RMSE1.setText(String.format("RMSE : %.4f%n-%s", rmseTr, errorLabel(rmseTr)));
            R3.setText(String.format("R2 : %.4f%n-%s", r2Tr, r2Label(r2Tr)));
            CORR1.setText(String.format("Correlation Coefficient : %.4f%n-%s", rTr, corrLabel(rTr)));

            MAE2.setText(String.format("MAE : %.4f%n-%s", maeTe, errorLabel(maeTe)));
            RMSE2.setText(String.format("RMSE : %.4f%n-%s", rmseTe, errorLabel(rmseTe)));
            R4.setText(String.format("R2 : %.4f%n-%s", r2Te, r2Label(r2Te)));
            CORR2.setText(String.format("Correlation Coefficient : %.4f%n-%s", rTe, corrLabel(rTe)));
            
            
            double month = Double.parseDouble(txtmonth.getText());

            DenseInstance test2 = new DenseInstance(data.numAttributes());
            test2.setDataset(data);
            test2.setValue(0, month);

            int trainCount = train.numInstances();
            int testCount = test.numInstances();
            
            dataset.setText(String.format("Training Data: %d", trainCount+testCount));
            trainNum.setText(String.format("Training Data: %d", trainCount));
            testNum.setText(String.format("Testing Data: %d", testCount));
            
            double prediction = model.classifyInstance(test2);

            lblprediction.setText("Predicted Sales: " + String.format("%.2f", prediction));

        }
        catch(Exception ex)
        {
            System.out.print(ex);
        }
    }//GEN-LAST:event_analyzeActionPerformed

