   private void loaddataset() {
        try {
            // raw CSV preview
            StringBuilder sb = new StringBuilder();
            try (BufferedReader br = new BufferedReader(new FileReader(CSV_FILE))) {
                String line;
                while ((line = br.readLine()) != null) {
                    sb.append(line).append("\n");
                }
            }
            txtcsv.setText(sb.toString());
            txtcsv.setCaretPosition(0);

            // load as Weka instances
            CSVLoader loader = new CSVLoader();
            loader.setSource(new File(CSV_FILE));
            data = loader.getDataSet();
            data.setClassIndex(data.numAttributes() - 1);

            // tabular view
            StringBuilder tab = new StringBuilder("Education\tYears Service\tPerformance\tPromotion\n");
            for (int i = 0; i < data.numInstances(); i++) {
                Instance in = data.instance(i);
                tab.append(String.format("%s\t%.0f\t%.0f\t%s\n",
                        in.stringValue(0), in.value(1), in.value(2), in.stringValue(3)));
            }
            txttabular.setText(tab.toString());
            txttabular.setCaretPosition(0);

            dataTotal.setText(String.format("Dataset Total: %d", data.numInstances()));
        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, "Cannot read " + CSV_FILE
                    + "\nMake sure it is in the main project folder.\n\n" + e.getMessage());
            e.printStackTrace();
        }
    }

