    private void analyzeActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_analyzeActionPerformed
        // TODO add your handling code here:

        try {
            if (data == null) {
                JOptionPane.showMessageDialog(this, "Dataset is not loaded.");
                return;
            }

            // ---- validate inputs ----
            String educInput = txteduc.getText().trim();
            String education = null;
            for (int i = 0; i < data.attribute(0).numValues(); i++) {
                if (data.attribute(0).value(i).equalsIgnoreCase(educInput)) {
                    education = data.attribute(0).value(i);
                }
            }
            if (education == null) {
    StringBuilder valid = new StringBuilder();
    for (int i = 0; i < data.attribute(0).numValues(); i++) {
        valid.append(data.attribute(0).value(i)).append("  ");
    }
    JOptionPane.showMessageDialog(this,
            "Education must be one of: " + valid
            + "\nYou entered: '" + educInput + "'"
            + "\nAttribute 0 is: " + data.attribute(0).name());
    return;
}
            double service, performance;
            try {
                service = Double.parseDouble(txtyearservice.getText().trim());
                performance = Double.parseDouble(txtperformance.getText().trim());
            } catch (NumberFormatException ex) {
                JOptionPane.showMessageDialog(this, "Year Service and Performance must be numbers.");
                return;
            }

            RandomForest model;
            Evaluation eval;
            String status;

            if (new File(MODEL_FILE).exists()) {
                // ---- LOAD saved model (no retraining) ----
                Object[] saved = SerializationHelper.readAll(MODEL_FILE);
                model = (RandomForest) saved[0];
                if (saved.length >= 3 && saved[2] instanceof Evaluation) {
                    eval = (Evaluation) saved[2];
                } else {
                    eval = new Evaluation(data);
                    eval.evaluateModel(model, data);
                }
                status = "Model LOADED from " + MODEL_FILE + " (no retraining)";
            } else {
    JOptionPane.showMessageDialog(this,
            "No saved model found (" + MODEL_FILE + ").\n"
            + "The model will now be trained, evaluated with 10-fold cross-validation, and saved.",
            "Model Not Found", JOptionPane.WARNING_MESSAGE);

    // ---- TRAIN + 10-fold cross-validation + SAVE ----
    model = new RandomForest();
    model.setNumIterations(100);
    model.buildClassifier(data);

    eval = new Evaluation(data);
    eval.crossValidateModel(new RandomForest(), data, 10, new Random(1));

    SerializationHelper.writeAll(MODEL_FILE,
            new Object[]{model, new Instances(data, 0), eval});
    status = "No saved model found. Model TRAINED and SAVED as " + MODEL_FILE;
}

            // ---- prediction ----
            Instance inst = new DenseInstance(data.numAttributes());
            inst.setDataset(data);
            inst.setValue(0, education);
            inst.setValue(1, service);
            inst.setValue(2, performance);
            double pred = model.classifyInstance(inst);
            lblprediction.setText("Prediction: " + data.classAttribute().value((int) pred).toUpperCase());

            // ---- metrics ----
            double accuracy = eval.pctCorrect();
            double precision = eval.weightedPrecision();
            double recall = eval.weightedRecall();
            double f1 = eval.weightedFMeasure();

            lblAccuracy.setText(String.format("Accuracy: %.2f%% - %s", accuracy, interpretAccuracy(accuracy)));
            lblPrecision.setText(String.format("Precision: %.4f - %s", precision, interpretRatio(precision)));
            lblRecall.setText(String.format("Recall: %.4f - %s", recall, interpretRatio(recall)));
            lblF1.setText(String.format("F1-Score: %.4f - %s", f1, interpretRatio(f1)));

            // ---- overall evaluation (F): good or poor ----
            boolean good = accuracy >= 80 && precision >= 0.80 && recall >= 0.80 && f1 >= 0.80;
            String overall = good ? "GOOD model performance" : "POOR model performance";

            txtConfusion.setText(status + "\n\n"
                    + eval.toMatrixString("===== 10-Fold Cross-Validation =====")
                    + "\nOverall Remark: " + overall);

            System.out.println("===== EVALUATION =====");
            System.out.println(eval.toSummaryString());
            System.out.println("Confusion Matrix:");
            System.out.println(eval.toMatrixString());

        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, "Error: " + e.getMessage());
            e.printStackTrace();
        }
    }//GEN-LAST:event_analyzeActionPerformed

