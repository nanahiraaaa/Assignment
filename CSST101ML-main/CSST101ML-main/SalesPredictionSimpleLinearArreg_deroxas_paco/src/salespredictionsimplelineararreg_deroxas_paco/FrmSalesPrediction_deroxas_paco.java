    private void loaddataset(){
    
        try{
        
            Instances data = DataSource.read("sales_deroxas_paco.arff");
            txtarff.setText(data.toString());

            String output = "Month\tSales\tData Set Size: 30\n";
            for(int i = 0; i < data.numInstances(); i++){
                double month = data.instance(i).value(0);
                double sales = data.instance(i).value(1);

                output += month + "\t" + sales + "\n";
            }
            txttabular.setText(output);
        }
        catch(Exception ex)
        {
            System.out.print(ex);
        }
    }
