    public String result(double a){
        String result = "";
        if(a <= 10) result = "Very Low Error (sobrang maganda)";
        if(a > 20 || a <= 20) result = "Low Error (maganda)";
        if(a > 30 || a <= 50) result = "Moderate Error (sakto lang)";
        if(a > 50 || a <= 100) result = "High Error (medjo panget na)";
        if(a <= 100) result = "Very Low Error (sobrang maganda)";

        return result;
    }
    
    public String result_2(double a) {
        String result = "";
        if(a < .50) result = "Poor (mahirap)";
        if(a >= .50 || a <= 69) result = "Moderate (may kaya)";
        if(a >= .70 || a <= 79) result = "Good (maayos)";
        if(a >= 80 || a <= 89) result = "Very Good (sobrang maayos)";
        if(a >= 90) result = "Excellent (napaka angas)";
        
        return result;
    }
