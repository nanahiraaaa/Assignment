    private void analyzeActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_analyzeActionPerformed
        // TODO add your handling code here:
        
        try{
            Instances data = DataSource.read("sales_deroxas_paco.arff");
            data.setClassIndex(1);
            SimpleLinearRegression model = new SimpleLinearRegression();
            model.buildClassifier(data);
            
            Evaluation eval = new Evaluation(data);
            eval.evaluateModel(model, data);
            
            double mae = eval.meanAbsoluteError();
            double rmse = eval.rootMeanSquaredError();
            double correlation =  eval.correlationCoefficient();
            double rSquared = correlation * correlation;
            
            
            
//            System.out.println("===== SIMPLE LINEAR REGRESSION EVALUATION =====");
            MAE.setText(String.format("MAE : %.4f%n-%s", mae, result(mae)));
            RMSE.setText(String.format("RMSE : %.4f%n-%s", rmse, result(rmse)));
            R2.setText(String.format("R2 : %.4f%n-%s", rSquared, result(rSquared)));
            CORR.setText(String.format("Correlation Coefficient : %.4f%n-%s", correlation, result_2(correlation)));
            
            double month = Double.parseDouble(txtmonth.getText());
            
            DenseInstance test = new DenseInstance(data.numAttributes());
            test.setDataset(data);
            test.setValue(0, month);
            
            double prediction = model.classifyInstance(test);
           
            lblprediction.setText("Predicted Sales: " + String.format("%.2f", prediction));

        }
        catch(Exception ex)
        {
            System.out.print(ex);
        }
    }//GEN-LAST:event_analyzeActionPerformed

