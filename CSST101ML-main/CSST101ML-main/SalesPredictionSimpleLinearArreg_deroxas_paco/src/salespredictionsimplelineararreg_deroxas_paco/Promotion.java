    private void analyzeActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_analyzeActionPerformed
        // TODO add your handling code here:

        try{
            Instances data = DataSource.read(datas);
            data.setClassIndex(data.numAttributes() - 1);
            dataTotal.setText(String.format("Dataset Total: %d", data.numInstances()));
            RandomForest model = new RandomForest();
            model.setNumIterations(100);
            model.buildClassifier(data);
            
            Evaluation eval = new Evaluation(data);
            eval.crossValidateModel(model, data, 10, new Random(1));
            
            // New Employee
            Instance employee = new DenseInstance(data.numAttributes());
            employee.setDataset(data);
            
            employee.setValue(0, txteduc.getText());
            employee.setValue(1, Double.parseDouble(txtservice.getText()));
            employee.setValue(2, Double.parseDouble(txtperformance.getText()));
            
            double prediction = model.classifyInstance(employee);
            String result = data.classAttribute().value((int) prediction);
            lblprediction.setText("Prediction: " + result);
            
            
            //Evaluation Metrics
            
            double Accuracy = eval.pctCorrect();
            double Precision = eval.weightedPrecision();
            double Recall = eval.weightedRecall();
            double F1 = eval.weightedFMeasure();
            
            lblAccuracy.setText("Accuracy: " + Accuracy + "% - " + interpretAccuracy(Accuracy));
            lblPrecision.setText("Precision: " + Precision + "% - " + interpretPrecision(Precision));
            lblRecall.setText("Recall: " + Recall + " - " + interpretRecall(Recall));
            lblF1.setText("F1-Score: " + Precision + " - " + interpretF1Score(F1));
            txtConfusion.setText(eval.toMatrixString());
            
            System.out.println("\n===== EVALUATION =====");
            System.out.println("Accuracy: " + eval.pctCorrect() + "%");
            System.out.println("Precision: " + eval.weightedPrecision());
            System.out.println("Recall: " + eval.weightedRecall());
            System.out.println("F1-Score: " + eval.weightedFMeasure());
            System.out.println("\nConfusion Matrix:");
            System.out.println(eval.toMatrixString());      
            

        }
        catch(Exception ex)
        {
            System.out.print(ex);
        }
    }//GEN-LAST:event_analyzeActionPerformed

